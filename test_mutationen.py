def laufkopie():
    """Temp-Kopie der Quelldateien; Symlinks werden nicht mitgenommen."""
    ziel = tempfile.mkdtemp(prefix="rag-mutationen-")
    for muster in KOPIEREN:
        for quelle in glob.glob(os.path.join(BASE, muster)):
            if os.path.islink(quelle):
                continue
            shutil.copy(quelle, ziel)
    os.makedirs(os.path.join(ziel, "pdfs"))
    # Messwerkzeug (nur Code, keine Daten)
    os.makedirs(os.path.join(ziel, "messung"))
    for quelle in glob.glob(os.path.join(BASE, "messung", "*.py")):
        if not os.path.islink(quelle):
            shutil.copy(quelle, os.path.join(ziel, "messung"))
    # Messergebnis der Vorab-Messung (nur Zahlen und Versionen, REQ-MB-18/-23): test_mehrbuch prueft es
    for rel in VORABMESSUNG:
        quelle = os.path.join(BASE, rel)
        if os.path.isfile(quelle) and not os.path.islink(quelle):
            os.makedirs(os.path.dirname(os.path.join(ziel, rel)), exist_ok=True)
            shutil.copy(quelle, os.path.join(ziel, rel))
    _git_nur_lesend(ziel)
    return ziel


def _git_nur_lesend(ziel):
    """Leeres git-Repo in der Laufkopie, das die Objekte des echten Repos nur LIEST (alternates).

    test_mehrbuch (REQ-MB-19) holt rag.py aus dem Basis-Commit per `git -C <Kopie> show` -- ohne
    Historie waere dieser Test in jeder Laufkopie rot und damit jede Mutation scheinbar gefangen.
    Ins echte Repo wird nichts geschrieben: neue Objekte landen in der Kopie."""
    p = subprocess.run(["git", "-C", BASE, "rev-parse", "--path-format=absolute", "--git-common-dir"],
                       capture_output=True, text=True)
    if p.returncode:
        return                                   # ohne git: der Basistest meldet sich selbst
    subprocess.run(["git", "init", "-q", ziel], check=True, capture_output=True)
    with open(os.path.join(ziel, ".git", "objects", "info", "alternates"), "w") as f:
        f.write(os.path.join(p.stdout.strip(), "objects") + "\n")
